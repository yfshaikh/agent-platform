"""End-to-end check of the core platform on a live cluster (Chunk A "done when").

Needs: platform installed (deploy/platform), example agents applied (deploy/examples). Real model + tool calls
cost a fraction of a cent. Run from agent-platform/:  uv run --project runtime python deploy/e2e_chunk_a.py
"""
import base64
import json
import socket
import subprocess
import sys
import time

import httpx

CONTEXT = "kind-f1"
NAMESPACE = "team-demo"
PROBE = f"probe-{int(time.time()) % 100000}"  # fresh name per run: daily token budgets persist in Postgres
results = []


def kubectl(*arguments, stdin=None, check=True):
    """Run kubectl against the test cluster; return stdout."""
    completed = subprocess.run(["kubectl", "--context", CONTEXT, *arguments], input=stdin, capture_output=True, text=True)
    if check and completed.returncode != 0:
        raise RuntimeError(completed.stderr.strip())
    return completed.stdout


def record(name, passed, detail=""):
    """Print and remember one check's result."""
    results.append(bool(passed))
    print(f"{'PASS' if passed else 'FAIL'}  {name}" + (f"  ({detail})" if detail else ""), flush=True)


def caller_token():
    """The namespace's caller token (generated by the operator for this test namespace)."""
    data = json.loads(kubectl("get", "secret", "agent-caller-token", "-n", NAMESPACE, "-o", "json"))["data"]
    return base64.b64decode(data["AGENT_CALLER_TOKEN"]).decode()


def free_port():
    """An unused local port for kubectl port-forward."""
    with socket.socket() as probe:
        probe.bind(("127.0.0.1", 0))
        return probe.getsockname()[1]


class Agent:
    """Port-forward to one agent's Service and call it like the platform API would."""

    def __init__(self, name, token):
        """Start the port-forward and wait until the agent answers /healthz."""
        self.port = free_port()
        self.process = subprocess.Popen(["kubectl", "--context", CONTEXT, "-n", NAMESPACE, "port-forward",
                                         f"svc/agent-{name}", f"{self.port}:80"], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        self.headers = {"Authorization": f"Bearer {token}"}
        for _ in range(60):
            try:
                httpx.get(f"http://127.0.0.1:{self.port}/healthz", timeout=2)
                return
            except httpx.HTTPError:
                time.sleep(0.5)
        raise RuntimeError(f"agent {name} not reachable")

    def post(self, path, body, headers=None):
        """POST to the agent; returns (status code, JSON body)."""
        response = httpx.post(f"http://127.0.0.1:{self.port}{path}", json=body, headers=headers or self.headers, timeout=180)
        return response.status_code, response.json()

    def close(self):
        """Stop the port-forward."""
        self.process.terminate()


def wait_for_agent(name, phase="Running", timeout=90):
    """Wait until an Agent's status reaches a phase; returns its status."""
    deadline = time.time() + timeout
    while time.time() < deadline:
        status = json.loads(kubectl("get", "agent", name, "-n", NAMESPACE, "-o", "json")).get("status", {})
        if status.get("phase") == phase:
            return status
        time.sleep(2)
    return status


def pod_can_reach(agent_name, host, port):
    """Open a TCP connection from inside an agent's pod (its NetworkPolicy applies). True if it connects."""
    pod = kubectl("get", "pod", "-n", NAMESPACE, "-l", f"platform.hacktx.dev/agent={agent_name}", "-o", "jsonpath={.items[0].metadata.name}")
    code = (f"import socket,sys\ns=socket.socket();s.settimeout(4)\n"
            f"try:\n s.connect(('{host}',{port}));print('open')\nexcept Exception as e:\n print('blocked',type(e).__name__)")
    return kubectl("exec", "-n", NAMESPACE, pod, "--", "python", "-c", code, check=False).strip().startswith("open")


def apply_agent(name, spec):
    """Create or update a test Agent in the test namespace."""
    kubectl("apply", "-f", "-", stdin=json.dumps({"apiVersion": "platform.hacktx.dev/v1", "kind": "Agent",
                                                   "metadata": {"name": name, "namespace": NAMESPACE}, "spec": spec}))


def tool_steps(trace):
    """Just the tool steps of a trace."""
    return [step for step in trace.get("steps", []) if step["type"] == "tool"]


def main():
    """Run every check, then exit non-zero if any failed."""
    token = caller_token()

    # 1. A real model uses a real read-only tool through the platform.
    researcher = Agent("researcher", token)
    status, trace = researcher.post("/chat", {"message": "What's the cheapest current price for Sony WH-1000XM6 headphones? One line."})
    used = [step["name"] for step in tool_steps(trace)]
    record("researcher answers using SerpApi", status == 200 and trace["status"] == "answered" and any("serpapi__" in name for name in used),
           f"tools {used}; answer: {trace.get('answer', '')[:90]!r}")
    status, _ = researcher.post("/chat", {"message": "hi"}, headers={"Authorization": "Bearer wrong"})
    record("agent rejects callers without the caller token", status == 401, f"HTTP {status}")

    # 2. A sensitive tool pauses for a human. (Approving now needs a grant signed by the platform API: see e2e_chunk_b.py.)
    bank = Agent("bank-assistant", token)
    status, paused = bank.post("/chat", {"message": "Please move $20 from my checking to my savings account."})
    record("transfer pauses for human approval", paused.get("status") == "awaiting_approval" and paused.get("tool") == "nessie__transfer_money",
           f"status {paused.get('status')}, arguments {paused.get('arguments')}")

    # 3. Policy, budgets and messaging with the zero-cost fake model (deterministic).
    apply_agent(PROBE, {"model": "fake", "instructions": "test", "tools": [{"name": "nessie", "allow": ["get_balance"]}],
                          "talksTo": ["researcher"], "budget": {"tokensPerDay": 450}})
    wait_for_agent(PROBE)
    probe = Agent(PROBE, token)
    status, trace = probe.post("/chat", {"message": 'CALL nessie__transfer_money {"from_account_id":"a","to_account_id":"b","amount":1,"description":"x"}'})
    record("tool outside the allow list is refused", tool_steps(trace)[0]["result"].startswith("refused: nessie__transfer_money is not one of your tools"),
           tool_steps(trace)[0]["result"][:80])
    status, trace = probe.post("/chat", {"message": 'CALL nessie__get_balance {"account_id":"f26755f9-dfc1-4062-9234-8395cd1d16af"}'})
    record("allowed read tool runs", '"balance"' in tool_steps(trace)[0]["result"], tool_steps(trace)[0]["result"][:80])
    status, trace = probe.post("/chat", {"message": 'CALL platform__send_message {"to":"researcher","text":"reply with the single word: pong"}'})
    record("agent messages an agent it talksTo", bool(tool_steps(trace)) and tool_steps(trace)[0]["result"] and not tool_steps(trace)[0]["result"].startswith(("refused", "message not")),
           tool_steps(trace)[0]["result"][:80] if tool_steps(trace) else trace.get("status"))
    status, trace = probe.post("/chat", {"message": "hi"})
    status, trace = probe.post("/chat", {"message": "hi"})
    record("daily token budget stops the agent", trace["status"] == "budget_exceeded", trace.get("answer", "")[:80])

    # 4. NetworkPolicy: the researcher (serpapi only) can't even open a connection to the Nessie tool.
    reach_serpapi = pod_can_reach("researcher", "tool-serpapi.platform.svc", 8000)
    reach_nessie = pod_can_reach("researcher", "tool-nessie.platform.svc", 8000)
    record("NetworkPolicy: researcher reaches its own tool", reach_serpapi)
    record("NetworkPolicy: researcher is blocked from tools it didn't list", not reach_nessie)
    record("NetworkPolicy: bank can't reach the researcher (no talksTo)", not pod_can_reach("bank-assistant", "agent-researcher", 80))

    # 5. The operator refuses to loosen a sensitive tool outside a simulation namespace.
    apply_agent("loose", {"model": "fake", "instructions": "test", "tools": [{"name": "nessie", "approval": {"transfer_money": "auto"}}]})
    status = wait_for_agent("loose", "Failed", timeout=30)
    record("operator rejects auto-approving a sensitive tool", status.get("phase") == "Failed", status.get("message", "")[:100])

    # 6. Kill switch and cleanup: replicas 0 stops it; deleting the Agent deletes everything it owned.
    kubectl("patch", "agent", PROBE, "-n", NAMESPACE, "--type", "merge", "-p", '{"spec":{"replicas":0}}')
    status = wait_for_agent(PROBE, "Stopped", timeout=60)
    record("kill switch (replicas: 0) stops the agent", status.get("phase") == "Stopped")
    for agent in (researcher, bank, probe):
        agent.close()
    kubectl("delete", "agent", PROBE, "loose", "-n", NAMESPACE)
    time.sleep(8)
    leftovers = kubectl("get", "deploy,svc,sa,secret,networkpolicy", "-n", NAMESPACE, "-o", "name", "-l", f"platform.hacktx.dev/agent={PROBE}")
    record("deleting an Agent deletes everything it owned", leftovers.strip() == "", leftovers.strip().replace("\n", ", "))

    print(f"\n{sum(results)}/{len(results)} checks passed")
    sys.exit(0 if all(results) else 1)


if __name__ == "__main__":
    main()
